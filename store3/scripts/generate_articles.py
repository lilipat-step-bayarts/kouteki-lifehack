def main():
    os.makedirs(ARTICLES_DIR, exist_ok=True)

    existing_articles = []
    if os.path.exists(JSON_PATH):
        try:
            with open(JSON_PATH, "r", encoding="utf-8") as f:
                existing_articles = json.load(f)
        except Exception:
            existing_articles = []

    existing_slugs = {a["slug"]: a for a in existing_articles}

    # 1. 初期記事データの書き込み・更新
    for item in INITIAL_ARTICLES_DATA:
        meta = item["meta"]
        slug = meta["slug"]
        md_path = os.path.join(ARTICLES_DIR, f"{slug}.md")
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(item["markdown"].strip() + "\n")
        existing_slugs[slug] = meta

    # 2. 日次ストックから未追加があれば1件追加
    for pool_item in DAILY_POOL:
        slug = pool_item["meta"]["slug"]
        if slug not in existing_slugs:
            meta = dict(pool_item["meta"])
            meta["date"] = TODAY_STR
            md_path = os.path.join(ARTICLES_DIR, f"{slug}.md")
            with open(md_path, "w", encoding="utf-8") as f:
                f.write(pool_item["markdown"].strip() + "\n")
            existing_slugs[slug] = meta
            print(f"Added daily pool article for Store 3: {slug}")
            break

    # 日付降順でソートして保存
    all_list = sorted(existing_slugs.values(), key=lambda x: x.get("date", ""), reverse=True)
    with open(JSON_PATH, "w", encoding="utf-8") as f:
        json.dump(all_list, f, ensure_ascii=False, indent=2)

    print(f"✅ Store 3 articles generated ({len(all_list)} articles total).")


if __name__ == "__main__":
    main()
